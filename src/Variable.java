public class Variable {
    public static void main(String[] args) {

        // create // declare
        int age1;
        age1 = 16;
        System.out.println(age1);

        // define pr initialize
        int maxmarks = 65;
        System.out.println(maxmarks);

        //Case sensitive
        int weight = 43;
        int Weight = 76;
        System.out.println("weight " + weight );
        System.out.println("Weight " + Weight );

        //Starting letter
        int marks = 76;
        int Marks = 67;
        int _marks = 87;
        int $marks = 34;
        System.out.println(marks + " " + Marks + " " + _marks + " " + $marks);
    }
}
